import { describe, expect, it } from 'vitest';
import type { OrgIdentity, SalesforceObjectSummary } from '@varkole/shared';
import { buildAutomaticAiContext, normalizeAiContextQuery, parseAiReadPlan } from './ai-context';

const objects: SalesforceObjectSummary[] = [
  {
    name: 'Account',
    label: 'Accounts',
    custom: false,
    queryable: true,
    searchable: true,
  },
  {
    name: 'Invoice__c',
    label: 'Invoices',
    custom: true,
    queryable: true,
    searchable: true,
  },
  {
    name: 'SocioWatch_Mention__c',
    label: 'SocioWatch Mentions',
    custom: true,
    queryable: true,
    searchable: true,
  },
];

describe('normalizeAiContextQuery', () => {
  it('adds a safe record limit', () => {
    expect(normalizeAiContextQuery('SELECT Id, Name FROM Account')).toBe(
      'SELECT Id, Name FROM Account LIMIT 20',
    );
  });

  it('keeps an explicit safe limit', () => {
    expect(normalizeAiContextQuery('SELECT Id FROM Contact LIMIT 200')).toBe(
      'SELECT Id FROM Contact LIMIT 200',
    );
  });

  it('rejects large and non-read-only context', () => {
    expect(() => normalizeAiContextQuery('SELECT Id FROM Account LIMIT 201')).toThrow('LIMIT 1');
    expect(() => normalizeAiContextQuery('DELETE FROM Account')).toThrow('read-only SELECT');
    expect(() => normalizeAiContextQuery('SELECT Id FROM Account; SELECT Id FROM Contact')).toThrow(
      'multiple SOQL',
    );
  });
});

describe('parseAiReadPlan', () => {
  it('canonicalizes accessible object labels and bounds safe queries', () => {
    expect(
      parseAiReadPlan(
        '```json\n{"objects":["Accounts","Unknown"],"queries":["SELECT Id, Name FROM Account"]}\n```',
        objects,
      ),
    ).toEqual({
      objects: ['Account'],
      queries: ['SELECT Id, Name FROM Account LIMIT 20'],
    });
  });

  it('drops any non-read-only query generated by the provider', () => {
    expect(parseAiReadPlan('{"objects":[],"queries":["DELETE FROM Account"]}', objects)).toEqual({
      objects: [],
      queries: [],
    });
  });

  it('resolves a conversational object name to the accessible Salesforce object', () => {
    expect(
      parseAiReadPlan(
        '{"objects":["SocioWatch__c"],"queries":["SELECT FIELDS(STANDARD) FROM SocioWatch__c LIMIT 20"]}',
        objects,
      ),
    ).toEqual({
      objects: ['SocioWatch_Mention__c'],
      queries: ['SELECT FIELDS(STANDARD) FROM SocioWatch_Mention__c LIMIT 20'],
    });
  });

  it('describes an object used by a query even when the provider omits the objects list', () => {
    expect(
      parseAiReadPlan(
        '{"objects":[],"queries":["SELECT FIELDS(STANDARD) FROM Invoice__c LIMIT 10"]}',
        objects,
      ),
    ).toEqual({
      objects: ['Invoice__c'],
      queries: ['SELECT FIELDS(STANDARD) FROM Invoice__c LIMIT 10'],
    });
  });
});

describe('buildAutomaticAiContext', () => {
  it('preserves a complete small roster before reducing background metadata', () => {
    const org: OrgIdentity = {
      key: 'org:user',
      orgId: '00D000000000001',
      userId: '005000000000001',
      username: 'admin@example.com',
      displayName: 'Admin',
      organizationName: 'Example',
      instanceUrl: 'https://example.my.salesforce.com',
      loginUrl: 'https://login.salesforce.com',
      environment: 'production',
      alias: '',
      apiVersion: '68.0',
      connectedAt: '2026-11-05T00:00:00.000Z',
      lastUsedAt: '2026-11-05T00:00:00.000Z',
      connected: true,
      connectionSource: 'browser-session',
    };
    const manyObjects = Array.from({ length: 400 }, (_, index) => ({
      name: `Object_${index}__c`,
      label: `Object ${index}`,
      custom: true,
      queryable: true,
      searchable: true,
    }));
    const records = Array.from({ length: 19 }, (_, index) => ({ Name: `User ${index + 1}` }));

    const context = JSON.parse(
      buildAutomaticAiContext({
        org,
        objects: manyObjects,
        describes: [],
        observations: [
          {
            query: 'SELECT Name FROM User LIMIT 200',
            result: { totalSize: 19, done: true, records, elapsedMs: 10 },
          },
        ],
        focus: 'Give me all users',
      }),
    ) as { readOnlyLookups: { includedRecords: number; truncated: boolean; records: unknown[] }[] };

    expect(context.readOnlyLookups[0]).toMatchObject({
      includedRecords: 19,
      truncated: false,
    });
    expect(context.readOnlyLookups[0]?.records).toHaveLength(19);
  });
});
